#!/usr/bin/env tsx

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import process from "node:process";

import { format } from "prettier";

import { SUPPORTED_LOCALES } from "../src/lib/i18n/config";
import { getMessages } from "../src/lib/i18n/messages";
import { productUiLabelBuilders } from "../src/lib/product-ui-labels/manifest";
import { createScriptLogger } from "./shared/logger";

const ROOT = resolve(import.meta.dirname, "..");
const OUTPUT = resolve(
  ROOT,
  "packages",
  "product-ui",
  "src",
  "labels",
  "generated.ts",
);
const rlog = createScriptLogger();

async function main() {
  const labelsByLocale: Record<string, Record<string, unknown>> = {};
  for (const locale of SUPPORTED_LOCALES) {
    const messages = getMessages(locale);
    labelsByLocale[locale] = Object.fromEntries(
      Object.entries(productUiLabelBuilders).map(([key, build]) => [
        key,
        build(messages),
      ]),
    );
  }

  const source = [
    "// @generated by scripts/generate-product-ui-labels.ts from src/i18n/*.yaml. Do not edit.",
    `export const productUiLabels = ${JSON.stringify(labelsByLocale)} as const;`,
    "export type ProductUiLabelLocale = keyof typeof productUiLabels;",
    "export type ProductUiLabels = (typeof productUiLabels)[ProductUiLabelLocale];",
    "",
  ].join("\n");
  const content = await format(source, { filepath: OUTPUT });

  let existing: string | null = null;
  try {
    existing = readFileSync(OUTPUT, "utf8");
  } catch {
    // A missing output is generated below.
  }
  if (existing === content) {
    rlog.success(`Product UI labels unchanged: ${OUTPUT}`);
    return;
  }
  writeFileSync(OUTPUT, content, "utf8");
  rlog.success(`Generated ${OUTPUT}`);
}

main().catch((error: unknown) => {
  rlog.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
});
