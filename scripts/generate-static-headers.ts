import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const HEADER_MARKER = "# Generated by InsightFlare; do not edit.";
const STATIC_HEADERS = [
  HEADER_MARKER,
  "# Vite content-hashed assets and versioned Flagpack SVGs only.",
  "/assets/*",
  "  Cache-Control: public, max-age=31536000, immutable",
  "/images/flagpack/*",
  "  Cache-Control: public, max-age=31536000, immutable",
  "",
].join("\n");

/** Never apply an immutable cache policy to HTML, API or unversioned public files. */
export async function generateStaticHeaders(publicDir: string): Promise<void> {
  const target = path.join(publicDir, "_headers");
  const existing = await readFile(target, "utf8").catch(
    (error: NodeJS.ErrnoException) => {
      if (error.code === "ENOENT") return null;
      throw error;
    },
  );
  if (existing === STATIC_HEADERS) return;
  if (existing !== null && !existing.startsWith(HEADER_MARKER)) {
    throw new Error("Refusing to overwrite a custom public/_headers file");
  }
  await writeFile(target, STATIC_HEADERS);
}
